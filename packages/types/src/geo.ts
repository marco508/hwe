/** Devise d'un pays (code ISO, insensible à la casse), sinon `fallback`. */
export function currencyOfCountry(code: string | null | undefined, fallback = "EUR"): string {
  if (!code) return fallback;
  return COUNTRY_CURRENCY[String(code).trim().toUpperCase()] ?? fallback;
}

