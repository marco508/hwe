/** Formes usuelles préférées à celles de la CLDR, par langue. */
const COUNTRY_OVERRIDES: Record<string, Record<string, string>> = {
  en: { CD: "DR Congo", CG: "Congo", CI: "Ivory Coast" },
};

const regionNames = new Map<string, Intl.DisplayNames | null>();

/**
 * Nom d'un pays dans la langue `lang` (« fr », « en », « ar »…).
 * Accepte un code ISO ; une valeur qui n'est pas un code est renvoyée telle quelle.
 */
export function countryName(code: string | null | undefined, lang = "fr", frName?: string): string {
  if (!code) return "";
  const upper = String(code).trim().toUpperCase();
  if (!/^[A-Z]{2}$/.test(upper)) return String(code);
  if (lang === "fr") return frName || COUNTRY_NAMES_FR[upper] || intlRegion(upper, "fr") || upper;
  const o = COUNTRY_OVERRIDES[lang]?.[upper];
  if (o) return o;
  return intlRegion(upper, lang) || frName || COUNTRY_NAMES_FR[upper] || upper;
}

function intlRegion(code: string, lang: string): string | null {
  let f = regionNames.get(lang);
  if (f === undefined) {
    try {
      f = new Intl.DisplayNames([lang], { type: "region" });
    } catch {
      f = null; // environnement sans ICU complet
    }
    regionNames.set(lang, f);
  }
  try {
    const n = f?.of(code);
    return n && n !== code ? n : null;
  } catch {
    return null;
  }
}
